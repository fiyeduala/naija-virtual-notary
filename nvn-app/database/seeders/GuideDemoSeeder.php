    /**
     * A one-page affidavit, invented, generated by TCPDF.
     *
     * Passing the notary's marks returns the sealed version of the same page,
     * which is what the client ends up with.
     *
     * @param  array<string, string>  $marks  type => stored path, or [] for the plain upload
     */
    private function affidavitPdf(NotarizationRequest $request, array $marks = []): string
    {
        $intake = (array) ($request->intake_data ?? []);
        $name   = trim(($intake['first_name'] ?? 'A') . ' ' . ($intake['last_name'] ?? 'Client'));

        $pdf = new \TCPDF();
        $pdf->SetCreator('GuideDemoSeeder');
        $pdf->SetAuthor('Naija Virtual Notary');
        $pdf->SetTitle('Affidavit (sample)');
        $pdf->setPrintHeader(false);
        $pdf->setPrintFooter(false);
        $pdf->AddPage();

        $pdf->SetFont('times', 'B', 15);
        $pdf->Cell(0, 12, 'AFFIDAVIT', 0, 1, 'C');
        $pdf->Ln(6);

        $pdf->SetFont('times', '', 12);
        $pdf->MultiCell(0, 7, 'I, ' . $name . ', of 14 Ogunlana Drive, Surulere, Lagos State, '
            . 'do hereby make oath and state as follows:', 0, 'L');
        $pdf->Ln(4);

        $clauses = [
            'That I am the deponent herein and a citizen of the Federal Republic of Nigeria.',
            'That the facts stated in this affidavit are within my personal knowledge.',
            'That this is a sample document, generated for a tutorial. It attests to nothing '
                . 'and concerns no real person.',
            'That I make this statement in good faith, believing the same to be true and correct, '
                . 'and in accordance with the Oaths Act.',
        ];

        foreach ($clauses as $i => $clause) {
            $pdf->MultiCell(0, 7, ($i + 1) . '.  ' . $clause, 0, 'L');
            $pdf->Ln(3);
        }

        $pdf->Ln(14);
        $pdf->Cell(0, 7, '_____________________________', 0, 1, 'L');
        $pdf->Cell(0, 7, 'DEPONENT', 0, 1, 'L');
        $pdf->Ln(16);
        $pdf->Cell(0, 7, 'SWORN TO at the Notary Public Office, Lagos', 0, 1, 'L');
        $pdf->Cell(0, 7, 'this ______ day of ______________________', 0, 1, 'L');
        $pdf->Ln(18);
        $pdf->Cell(0, 7, 'BEFORE ME', 0, 1, 'L');
        $pdf->Ln(22);
        $pdf->Cell(0, 7, '_____________________________', 0, 1, 'L');
        $pdf->Cell(0, 7, 'NOTARY PUBLIC', 0, 1, 'L');

        if ($marks !== []) {
            // Where the editor's own screenshot puts them: the hand on the
            // notary's line, the stamp beside it, the seal clear of both.
            $at = [
                'signature' => [26, 232, 46, 0],
                'stamp'     => [92, 230, 52, 0],
                'seal'      => [152, 224, 34, 34],
            ];

            foreach ($at as $type => [$x, $y, $w, $h]) {
                if (! isset($marks[$type]) || ! Storage::disk('private')->exists($marks[$type])) {
                    continue;
                }

                // '@' hands TCPDF the bytes directly, so nothing has to be
                // copied out of private storage onto a temporary file.
                $pdf->Image('@' . Storage::disk('private')->get($marks[$type]), $x, $y, $w, $h, 'PNG');
            }

            $pdf->SetXY(14, 272);
            $pdf->SetFont('helvetica', '', 8);
            $pdf->Cell(0, 5, 'Notarized via Naija Virtual Notary — ' . $request->reference
                . ' — ' . now()->format('j M Y'), 0, 1, 'L');
        }

        return $pdf->Output('affidavit.pdf', 'S');
    }

