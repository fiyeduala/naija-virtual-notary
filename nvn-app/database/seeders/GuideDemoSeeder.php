    /**
     * The document being notarized, the client's ID, and their own signature.
     *
     * The signature is deliberately present: the editor offers a separate
     * client-signature tool when one exists, and that tool is a section of the
     * guide. Without this row the screenshot could not show it.
     */
    private function attachDocuments(NotarizationRequest $request, int $uploadedBy): void
    {
        if ($request->documents()->exists()) {
            return;
        }

        $files = [
            ['document',         'affidavit.pdf',         $this->affidavitPdf($request)],
            ['identification',   'identification.png',    $this->idCard()],
            ['client_signature', 'client-signature.png',  $this->clientSignature()],
        ];

        foreach ($files as [$type, $name, $bytes]) {
            $path = 'request-documents/guide-' . $request->id . '-' . $type . '.' . pathinfo($name, PATHINFO_EXTENSION);
            Storage::disk('private')->put($path, $bytes);

            RequestDocument::create([
                'request_id'        => $request->id,
                'uploaded_by'       => $uploadedBy,
                'file_url'          => $path,
                'original_filename' => $name,
                'file_hash_sha256'  => hash('sha256', $bytes),
                'file_type'         => $type,
            ]);
        }
    }

    /*
    |--------------------------------------------------------------------------
    | The pictures, drawn rather than collected
    |--------------------------------------------------------------------------
    |
    | GD and TCPDF are both already dependencies, so the marks and the document
    | are generated here in a few lines. The alternative — keeping sample images
    | in the repository — is how a real seal ends up in version control.
    */

    /**
     * A signature, a stamp and a seal, written to the private disk.
     *
     * @return array<string, string>  type => stored path
     */
    private function drawMarks(): array
    {
        $marks = [
            'signature' => $this->signatureImage(),
            'stamp'     => $this->stampImage(),
            'seal'      => $this->sealImage(),
        ];

        $paths = [];

        foreach ($marks as $type => $bytes) {
            $path = 'notary-assets/guide-demo-' . $type . '.png';
            Storage::disk('private')->put($path, $bytes);
            $paths[$type] = $path;
        }

        return $paths;
    }

    /** An invented hand, drawn stroke by stroke on transparency. */
    private function signatureImage(): string
    {
        return $this->png(520, 170, function ($im) {
            $ink  = imagecolorallocate($im, 16, 32, 92);
            $base = 118.0;

            // Everything is sheared off the baseline on the way out, which is
            // what makes the whole hand lean the same way a written one does.
            $draw = function (callable $point, int $steps = 320) use ($im, $ink, $base) {
                $prev = null;

                for ($i = 0; $i <= $steps; $i++) {
                    [$x, $y] = $point($i / $steps);
                    $x += 0.22 * ($base - $y);

                    if ($prev !== null) {
                        imageline($im, (int) $prev[0], (int) $prev[1], (int) $x, (int) $y, $ink);
                    }

                    $prev = [$x, $y];
                }
            };

            // A capital is a near-closed loop with a gap where the pen lifts.
            $capital = function (float $cx, float $cy, float $rx, float $ry) {
                return function (float $u) use ($cx, $cy, $rx, $ry) {
                    $a = M_PI * (0.5 + 1.85 * $u);

                    return [$cx + $rx * sin($a), $cy + $ry * cos($a)];
                };
            };

            // And the run between capitals is an oscillation whose height dies
            // away, the way a hand loses its letters towards the end of a word.
            $run = function (float $x0, float $x1, float $waves, float $rise) use ($base) {
                return function (float $u) use ($x0, $x1, $waves, $rise, $base) {
                    $x = $x0 + ($x1 - $x0) * $u + 16 * sin(2 * M_PI * $waves * $u);
                    $y = $base
                        - 34 * (0.5 + 0.5 * cos(2 * M_PI * $waves * $u)) * exp(-1.1 * $u)
                        - $rise * $u;

                    return [$x, $y];
                };
            };

            imagesetthickness($im, 5);

            $draw($capital(78, 78, 34, 56));
            $draw($run(102, 236, 3.2, 6));
            $draw($capital(278, 76, 36, 58));
            $draw($run(304, 448, 3.6, 10));

            // The flourish underneath: part of the signature, not a rule.
            imagesetthickness($im, 4);
            $draw(function (float $u) {
                $x = 452 - 392 * $u + 46 * sin(M_PI * $u);
                $y = 104 + 44 * sin(M_PI * min(1.0, $u * 1.35));

                return [$x, $y];
            });
        });
    }

    /** A rectangular commissioner's stamp. */
    private function stampImage(): string
    {
        return $this->png(640, 260, function ($im) {
            $ink = imagecolorallocate($im, 122, 20, 24);

            imagesetthickness($im, 6);
            imagerectangle($im, 10, 10, 629, 249, $ink);
            imagesetthickness($im, 2);
            imagerectangle($im, 24, 24, 615, 235, $ink);

            $this->centre($im, 'NOTARY PUBLIC', 72, 26, $ink);
            $this->centre($im, 'ADAEZE NWACHUKWU', 118, 22, $ink);
            $this->centre($im, 'SCN/2019/004812', 160, 17, $ink);
            $this->centre($im, 'LAGOS, NIGERIA', 200, 17, $ink);
        });
    }

    /** A round seal, with its text set around the ring. */
    private function sealImage(): string
    {
        return $this->png(460, 460, function ($im) {
            $ink = imagecolorallocate($im, 18, 74, 36);
            [$cx, $cy] = [230, 230];

            imagesetthickness($im, 7);
            imageellipse($im, $cx, $cy, 440, 440, $ink);
            imagesetthickness($im, 3);
            imageellipse($im, $cx, $cy, 404, 404, $ink);
            imageellipse($im, $cx, $cy, 250, 250, $ink);

            // 'NOTARY PUBLIC' over the top, the country round the bottom, which is
            // how the ring on a real impression is read.
            $this->ring($im, 'NOTARY PUBLIC', 175, 0, 18, $ink);
            $this->ring($im, 'FEDERAL REPUBLIC OF NIGERIA', 191, 180, 15, $ink, true);

            $this->centre($im, 'ADAEZE', 198, 22, $ink, 460);
            $this->centre($im, 'NWACHUKWU', 228, 22, $ink, 460);
            $this->centre($im, 'LAGOS', 258, 16, $ink, 460);
        });
    }

    /** The client's own signature — a different hand from the notary's. */
    private function clientSignature(): string
    {
        return $this->png(460, 150, function ($im) {
            $ink = imagecolorallocate($im, 24, 24, 28);
            imagesetthickness($im, 4);

            $prev = null;

            for ($t = 0; $t <= 1000; $t++) {
                $u = $t / 1000;
                $x = 30 + $u * 400;
                $y = 86 - 34 * sin($u * M_PI * 2.2) - 11 * cos($u * M_PI * 9.1);

                if ($prev) {
                    imageline($im, (int) $prev[0], (int) $prev[1], (int) $x, (int) $y, $ink);
                }

                $prev = [$x, $y];
            }
        });
    }

