    public function run(): void
    {
        if (! app()->environment(['local', 'testing'])) {
            $this->command?->error(
                'GuideDemoSeeder writes users, requests and payment rows. It runs in local and testing only.'
            );

            return;
        }

        $marks   = $this->drawMarks();
        $notary  = $this->notary($marks);
        $clients = $this->clients();

        $this->freshNotary();

        $this->waitingJobs($notary, $clients);
        $this->queriedJob($notary, $clients[2]);
        $this->liveSession($notary, $clients[3]);
        $this->finishedWork($notary, $clients, $marks);
        $this->offsiteJob($notary);

        $this->command?->info('Guide demo scene built.');
        $this->command?->info('  Working partner: ' . self::NOTARY_EMAIL . ' / password');
        $this->command?->info('  Day one partner: ' . self::FRESH_EMAIL . ' / password');
    }

