    /**
     * One marketplace job, with the documents a client actually uploads.
     *
     * Keyed on the reference rather than created blind, so running the seeder a
     * second time refreshes the scene instead of doubling it.
     *
     * @param  array<string, mixed>  $attributes
     */
    private function job(
        NotaryProfile $notary,
        User $client,
        string $serviceType,
        RequestStatus $status,
        array $attributes,
    ): NotarizationRequest {
        $service = $notary->services->firstWhere('service_type', $serviceType);
        [$first, $last] = array_pad(explode(' ', $client->full_name, 2), 2, '');

        $request = NotarizationRequest::firstOrCreate(
            ['reference' => $attributes['reference']],
            array_merge([
                'client_id'    => $client->id,
                'notary_id'    => $notary->id,
                'service_id'   => $service?->id,
                'status'       => $status->value,
                'currency'     => 'NGN',
                'is_offsite'   => false,
                'document_use' => self::USES[$serviceType] ?? 'Local use',
                'intake_data'  => [
                    'first_name' => $first,
                    'last_name'  => $last,
                    'email'      => $client->email,
                    'phone'      => $client->phone,
                ],
                'submitted_at' => $attributes['created_at'] ?? now(),
            ], $attributes),
        );

        $this->attachDocuments($request, $client->id);

        return $request;
    }

    private const USES = [
        'Affidavit'             => 'Local — change of name',
        'Travel Consent Letter' => 'Abroad — visa application',
