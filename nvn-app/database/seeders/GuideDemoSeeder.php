/**
 * The scene the notary guide's screenshots were taken of.
 *
 * resources/views/notary/guide.blade.php shows a partner what each screen looks
 * like with work on it, which means somebody has to produce an empty dashboard
 * holding a job, a request mid-query, a session waiting on a call and a month of
 * earnings. Doing that by hand is an afternoon, and doing it twice is an
 * afternoon again — so it is a seeder, and the screenshots can be re-taken from
 * scratch the next time one of those screens changes.
 *
 * Everything in here is invented. The people do not exist, the document is
 * generated by this file, and the signature, stamp and seal are drawn by it in
 * code. That is not tidiness: a tutorial is a published document, and a real
 * client's name, a real notary's seal or a real affidavit appearing in one would
 * be a disclosure, not a typo. Nothing is read off disk and nothing is copied
 * from the live system.
 *
 * It refuses to run outside local and testing. The guard is not politeness
 * either — this writes users, requests and payments, and a payment row is read
 * by the payout ledger.
 */
