    /**
     * A month of finished work, so the earnings block has something to split.
     *
     * Completed with a successful NGN request_fee is the exact shape the payout
     * ledger counts — see Payment::scopePayable(). Anything looser would
     * photograph as zero earnings on a desk full of completed jobs.
     *
     * @param  array<int, User>  $clients
     */
    /** @param  array<string, string>  $marks  type => stored path */
    private function finishedWork(NotaryProfile $notary, array $clients, array $marks): void
    {
        $done = [
            ['Affidavit',             'NVN-2026-0402', 1500000, 26],
            ['Travel Consent Letter', 'NVN-2026-0417', 2500000, 19],
            ['Affidavit',             'NVN-2026-0434', 1500000, 12],
            ['Deed of Assignment',    'NVN-2026-0455', 6000000,  6],
            ['Affidavit',             'NVN-2026-0469', 1500000,  2],
        ];

        foreach ($done as $i => [$type, $reference, $amount, $daysAgo]) {
            $request = $this->job($notary, $clients[$i % count($clients)], $type, RequestStatus::Completed, [
                'reference'    => $reference,
                'paid_at'      => now()->subDays($daysAgo),
                'accepted_at'  => now()->subDays($daysAgo),
                'completed_at' => now()->subDays($daysAgo)->addHours(2),
                'created_at'   => now()->subDays($daysAgo),
            ]);

            Payment::firstOrCreate(
                ['request_id' => $request->id, 'type' => 'request_fee'],
                [
                    'user_id'            => $request->client_id,
                    'amount'             => $amount,
                    'currency'           => 'NGN',
                    'status'             => 'successful',
                    'paystack_reference' => 'PS-GUIDE-' . Str::upper(Str::random(10)),
                    'completed_at'       => now()->subDays($daysAgo),
                ],
            );

            $this->attachSealed($request, $notary, $marks);
        }
    }

    /**
     * The sealed PDF the notary issued, hung off the upload it was made from.
     *
     * Without this the completed list reads "No sealed document on this one"
     * against every row — which is the branch for a job closed by hand, and is
     * the opposite of what the guide is teaching.
     *
     * @param  array<string, string>  $marks  type => stored path
     */
    private function attachSealed(NotarizationRequest $request, NotaryProfile $notary, array $marks): void
    {
        if ($request->finalDocuments()->exists()) {
            return;
        }

        $source = $request->documents()->where('file_type', 'document')->orderBy('id')->first();
        $bytes  = $this->affidavitPdf($request, $marks);
        $path   = 'request-documents/guide-' . $request->id . '-sealed.pdf';

        Storage::disk('private')->put($path, $bytes);

        RequestDocument::create([
            'request_id'         => $request->id,
            'uploaded_by'        => $notary->user_id,
            'source_document_id' => $source?->id,
            'file_url'           => $path,
            'original_filename'  => 'affidavit-notarized.pdf',
            'file_hash_sha256'   => hash('sha256', $bytes),
            'file_type'          => 'document',
            'is_final_notarized' => true,
        ]);
    }

