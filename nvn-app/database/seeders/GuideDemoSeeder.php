    /**
     * A transparent PNG of the given size, drawn by the callback.
     *
     * Transparency matters rather than being a nicety: these images are stamped
     * onto a page of text, and a white box behind a seal covers the words it is
     * supposed to sit beside.
     */
    private function png(int $width, int $height, callable $draw): string
    {
        $im = imagecreatetruecolor($width, $height);
        imagesavealpha($im, true);
        imagealphablending($im, false);
        imagefill($im, 0, 0, imagecolorallocatealpha($im, 0, 0, 0, 127));
        imagealphablending($im, true);
        imageantialias($im, true);

        $draw($im);

        ob_start();
        imagepng($im);
        $bytes = (string) ob_get_clean();
        imagedestroy($im);

        return $bytes;
    }

    /** One line of text, centred across the image. */
    private function centre($im, string $text, int $y, int $size, int $colour, ?int $width = null): void
    {
        $font    = $this->font();
        $canvas  = $width ?? imagesx($im);

        if ($font === null) {
            // GD's own bitmap face: one fixed size, no rotation, but it needs
            // nothing installed. See font().
            $w = imagefontwidth(5) * mb_strlen($text);
            imagestring($im, 5, (int) (($canvas - $w) / 2), $y - 14, $text, $colour);

            return;
        }

        $box = imagettfbbox($size, 0, $font, $text);
        $w   = $box[2] - $box[0];

        imagettftext($im, $size, 0, (int) (($canvas - $w) / 2), $y, $colour, $font, $text);
    }

    /**
     * Text set around a circle, which is what makes a round seal look round.
     *
     * $start is the angle of the first glyph in degrees, measured the way a
     * clock face is read; $flip sets the lower half, where letters have to be
     * turned over or they come out upside down.
     */
    private function ring($im, string $text, int $radius, int $start, int $size, int $colour, bool $flip = false): void
    {
        $font = $this->font();

        if ($font === null) {
            // Nothing to rotate a glyph with, so the line goes across the ring
            // instead of around it. Still legible, still plainly a seal.
            $this->centre($im, $text, (int) (imagesy($im) / 2) + ($flip ? 150 : -130), $size, $colour);

            return;
        }

        $letters = preg_split('//u', $text, -1, PREG_SPLIT_NO_EMPTY) ?: [];
        $count   = count($letters);

        if ($count === 0) {
            return;
        }

        [$cx, $cy] = [imagesx($im) / 2, imagesy($im) / 2];

        // Letters are spaced by arc length, not by splitting a fixed angle
        // between them: the same word on a smaller ring has to be set tighter,
        // and dividing an angle gives the opposite of that.
        $step   = ($size * 0.95) / ($radius * M_PI / 180);
        $spread = $step * ($count - 1);

        foreach ($letters as $i => $letter) {
            // Bearing is clockwise from the top of the circle. The bottom arc
            // runs the other way round, because text there is read from the
            // outside left to right, which is anticlockwise from where we sit.
            $bearing = $flip
                ? $start + $spread / 2 - $i * $step
                : $start - $spread / 2 + $i * $step;

            $radians = deg2rad($bearing - 90);

            $x = $cx + $radius * cos($radians);
            $y = $cy + $radius * sin($radians);

            // imagettftext turns a glyph anticlockwise about its baseline
            // origin, so the angle wanted is the tangent — and half a turn more
            // on the bottom arc, or the letters come out standing on their
            // heads.
            $angle = $flip ? 180 - $bearing : -$bearing;

            imagettftext($im, $size, $angle, (int) $x, (int) $y, $colour, $font, $letter);
        }
    }

    /**
     * A TrueType face GD can set, or null if this machine has none to offer.
     *
     * Nothing is downloaded and nothing is committed: a font file in the
     * repository is a licence question, and the seeder is a development tool
     * that must not grow one. So it looks where the three desktop platforms
     * keep their own, and when it finds nothing the callers fall back to GD's
     * built-in bitmap face — the marks come out plainer, and the scene is still
     * seeded, which is what matters.
     *
     * NVN_GUIDE_FONT overrides it, for a machine whose fonts are somewhere else.
     */
    private function font(): ?string
    {
        static $resolved = false;
        static $path = null;

        if ($resolved) {
            return $path;
        }

        $resolved = true;

        if (! function_exists('imagettftext')) {
            return $path = null;
        }

        $candidates = array_filter([
            env('NVN_GUIDE_FONT'),
            'C:/Windows/Fonts/segoeui.ttf',
            'C:/Windows/Fonts/arial.ttf',
            '/System/Library/Fonts/Supplemental/Arial.ttf',
            '/Library/Fonts/Arial.ttf',
            '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',
            '/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf',
            '/usr/share/fonts/TTF/DejaVuSans.ttf',
        ]);

        foreach ($candidates as $candidate) {
            if (is_file($candidate)) {
                return $path = $candidate;
            }
        }

        $this->command?->warn('No TrueType font found; the demo marks will use GD\'s built-in face.');

        return $path = null;
    }
